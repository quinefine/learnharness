import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const cssPath = require.resolve("katex/dist/katex.min.css");
const root = cssPath.slice(0, -"katex.min.css".length);
let css = readFileSync(cssPath, "utf8");
const fonts = new Set([...css.matchAll(/url\(['"]?fonts\/([^)'"]+\.woff2)['"]?\)/g)].map((match) => match[1]));
for (const font of fonts) {
  const data = readFileSync(`${root}fonts/${font}`).toString("base64");
  css = css.replaceAll(`fonts/${font}`, `data:font/woff2;base64,${data}`);
}
const output = "// Generated by scripts/build-anki-katex-css.mjs. KaTeX CSS and WOFF2 fonts.\n" +
  `export const KATEX_CSS = ${JSON.stringify(css)};\n`;
writeFileSync(new URL("../src/server/anki-katex-css.ts", import.meta.url), output);
